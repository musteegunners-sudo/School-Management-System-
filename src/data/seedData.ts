function buildScore(
  id: string,
  studentId: string,
  subjectId: string,
  classId: string,
  sessionId: string,
  termId: string,
  ca1: number,
  ca2: number,
  exam: number,
  weeklyAssignments?: number[]
): ScoreRecord {
  const total = Math.min(100, Math.round(ca1 + ca2 + exam));
  let grade: 'A' | 'B' | 'C' | 'D' | 'E' | 'F' = 'F';
  let remark = 'Fail (Rasib)';

  if (total >= 70) {
    grade = 'A';
    remark = 'Distinction (Mumtaz)';
  } else if (total >= 60) {
    grade = 'B';
    remark = 'Very Good (Jayyid Jiddan)';
  } else if (total >= 50) {
    grade = 'C';
    remark = 'Good (Jayyid)';
  } else if (total >= 45) {
    grade = 'D';
    remark = 'Pass (Maqbool)';
  } else if (total >= 40) {
    grade = 'E';
    remark = 'Fair (Da\'eef)';
  }

  const unitTotal = weeklyAssignments ? weeklyAssignments.reduce((a, b) => a + b, 0) : Math.round((ca1 / 20) * 48);

  return {
    id,
    studentId,
    subjectId,
    classId,
    sessionId,
    termId,
    weeklyAssignments: weeklyAssignments || [4, 4, 3, 4, 4, 4, 3, 4, 4, 4, 3, 4],
    unitAssignmentTotal: unitTotal,
    ca1,
    ca2,
    exam,
    total,
    grade,
    remark,
  };
}

